// Write each brand's approved posts to `brand/approved-examples.md`.
//
// This is the file that makes "keep to the standard" mechanical rather than
// aspirational. The rubric says what we CHECK. The client's approved posts are
// what the standard IS, and until now nothing read them:
//
//   - draft-post has always had a slot for `brand/examples/`, and no brand ever
//     had that directory, so every draft was written from voice rules and
//     pillar definitions alone.
//   - grade-brand.mjs scored the client's own verbatim-approved work at 51-87 because
//     it had the criteria and not the standard. Feeding it three approved posts
//     moved the floor from 51 to 70 and killed the F and the D.
//
// One generated file, two consumers, and it maintains itself: the client approves in
// the hub, `hub-sync --pull` stamps it to disk, this rewrites the file, and the
// next draft is written against it.
//
//   node scripts/approved-corpus.mjs                 every brand
//   node scripts/approved-corpus.mjs --brand=clinic   one
//   node scripts/approved-corpus.mjs --dry-run       print what would change
//
// Env (.env.local): NEXT_PUBLIC_SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { resolveClientsRoot } from "../brain/post-grades-core.mjs";
import { cleanEnv } from "./lib/env.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
try { process.loadEnvFile(join(ROOT, ".env.local")); } catch { /* exported */ }

const DRY_RUN = process.argv.includes("--dry-run");
const ONLY_BRAND = (process.argv.find((a) => a.startsWith("--brand=")) || "").split("=")[1] || null;

const HOME = process.env.USERPROFILE ?? process.env.HOME;
const CLIENTS_ROOT = resolveClientsRoot(
  process.env.CLIENTS_ROOT
    ? [process.env.CLIENTS_ROOT]
    : [join(HOME, "Desktop", "Main Folder CLAUDE", "clients"), join(HOME, "Desktop", "clients")],
  existsSync,
);

export const FILENAME = "approved-examples.md";

/** Enough of a post to learn its shape; long enough to include the closer. */
const BODY_CAP = 3000;

/**
 * The file is generated, so it says so at the top, loudly. Someone editing it
 * by hand would lose the edit on the next approval and be right to be annoyed.
 */
export function renderCorpus(brand, posts, stampedAt) {
  const lines = [
    `# Approved examples: ${brand}`,
    "",
    "<!-- GENERATED by scripts/approved-corpus.mjs. Do not edit by hand: the next",
    "     client approval rewrites this file. To change what is here, change what",
    "     the client has approved in the hub. -->",
    "",
    `${posts.length} post${posts.length === 1 ? "" : "s"} the client approved without changes.`,
    "",
    "**These are the standard.** The rubric says what gets checked; these say what",
    "passing actually looks like in this brand's voice. Read them before drafting,",
    "and match their shape, their register and their level of specificity rather",
    "than writing to the rubric's criteria in the abstract.",
    "",
    `_Last written ${stampedAt}._`,
    "",
    "---",
    "",
  ];

  for (const [i, p] of posts.entries()) {
    const meta = [p.platform, p.pillar].filter(Boolean).join(" · ");
    lines.push(
      `## ${i + 1}. ${p.title ?? p.post_ref}`,
      "",
      `\`${p.post_ref}\`${meta ? ` — ${meta}` : ""}`,
      "",
      (p.body ?? "").trim().slice(0, BODY_CAP),
      "",
      "---",
      "",
    );
  }

  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** Read the generated file back, for anything that wants the examples as text. */
export function loadApprovedExamples(clientsRoot, brand) {
  const fp = join(clientsRoot, brand, "brand", FILENAME);
  return existsSync(fp) ? readFileSync(fp, "utf8") : null;
}

async function main() {
  const url = cleanEnv(process.env.NEXT_PUBLIC_SUPABASE_URL);
  const key = cleanEnv(process.env.SUPABASE_SERVICE_ROLE_KEY);
  if (!url || !key) {
    console.error("NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required.");
    process.exit(1);
  }
  const { createClient } = await import("@supabase/supabase-js");
  const sb = createClient(url, key, { auth: { persistSession: false } });

  let q = sb
    .schema("hub")
    .from("posts")
    .select("brand,post_ref,title,body,platform,pillar,client_reviewed_at")
    .eq("client_status", "approved")
    .order("brand")
    .order("post_ref");
  if (ONLY_BRAND) q = q.eq("brand", ONLY_BRAND);

  const { data: all, error } = await q;
  if (error) { console.error(error.message); process.exit(1); }
  // From 2026-09-09 Noah is Clinic's approver, so an approval after that means
  // "cleared to post", not the client signing off on the voice. Only his count here.
  // ponytail: a date cutoff, add an approved_by column if the client approves again.
  const data = all.filter((p) => p.brand !== "clinic" || !p.client_reviewed_at || p.client_reviewed_at < "2026-09-09");

  const byBrand = new Map();
  for (const p of data ?? []) {
    // A post with no body teaches nothing and would pad the prompt.
    if ((p.body ?? "").trim().length < 200) continue;
    byBrand.set(p.brand, [...(byBrand.get(p.brand) ?? []), p]);
  }

  if (!byBrand.size) {
    console.log("No approved posts yet. Nothing to write.");
    return;
  }

  // Passed in rather than read from the clock inside render, so the output is
  // testable and a re-run with no new approvals produces the same bytes.
  const stampedAt = new Date().toISOString().slice(0, 10);

  for (const [brand, posts] of byBrand) {
    const fp = join(CLIENTS_ROOT, brand, "brand", FILENAME);
    const next = renderCorpus(brand, posts, stampedAt);
    const prev = existsSync(fp) ? readFileSync(fp, "utf8") : null;

    // Compare ignoring the date line, so a no-op run does not churn the file.
    const strip = (s) => (s ?? "").replace(/^_Last written .*_$/m, "");
    if (prev !== null && strip(prev) === strip(next)) {
      console.log(`${brand}: unchanged (${posts.length} approved)`);
      continue;
    }

    console.log(`${brand}: ${posts.length} approved post(s)${DRY_RUN ? " (dry run)" : ""} → ${fp}`);
    if (DRY_RUN) continue;
    mkdirSync(dirname(fp), { recursive: true });
    writeFileSync(fp, next, "utf8");
  }
}

// Importable for tests without running the sync.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/").split("/").pop())) {
  await main();
}
